#!/usr/bin/env python3
"""Build site/learning/learning-data.json from the learning lab's Markdown (modules, quizzes, answer keys).

The Markdown stays the source of truth; the interactive page only renders this JSON.
  python3 scripts/build_learning.py          write the JSON
  python3 scripts/build_learning.py --check  fail if the committed JSON is out of date (CI)
"""
from __future__ import annotations

import json
import posixpath
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BLOB = "https://github.com/phlppgdfry/shipment-exception-management-business-analysis/blob/main/"
OUT = ROOT / "site/learning/learning-data.json"


def absolute_links(md: str, base_dir: str) -> str:
    def repl(m: re.Match) -> str:
        text, url = m.group(1), m.group(2)
        if re.match(r"^(https?:|mailto:|#)", url):
            return f"[{text}]({url})"
        path, _, anchor = url.partition("#")
        resolved = posixpath.normpath(posixpath.join(base_dir, path))
        return f"[{text}]({BLOB}{resolved}{'#' + anchor if anchor else ''})"
    return re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", repl, md)


def parse_quiz(text: str) -> list[dict]:
    out = []
    for block in re.split(r"^### ", text, flags=re.M)[1:]:
        lines = block.strip().splitlines()
        qid = lines[0].strip()
        options = [(m.group(1), m.group(2).strip()) for line in lines if (m := re.match(r"^- ([A-D])\) (.+)$", line))]
        question = " ".join(l.strip() for l in lines[1:] if l.strip() and not l.startswith("- "))
        out.append({"id": qid, "question": question, "options": [{"key": k, "text": t} for k, t in options]})
    return out


def parse_key(text: str, base_dir: str) -> dict[str, dict]:
    section = text.split("## Quiz", 1)[1].split("\n## ", 1)[0]
    out = {}
    for block in re.split(r"^### ", section, flags=re.M)[1:]:
        head, _, body = block.partition("\n")
        m = re.match(r"(Q\d+) — ([A-D])", head.strip())
        out[m.group(1)] = {"answer": m.group(2), "explanation": absolute_links(body.strip(), base_dir)}
    return out


def build() -> dict:
    modules = []
    for readme in sorted((ROOT / "learning/modules").glob("*/README.md")):
        slug = readme.parent.name
        md = readme.read_text(encoding="utf-8")
        title = re.search(r"^# (.+)$", md, re.M).group(1)
        meta = re.search(r"^> (.+)$", md, re.M).group(1)
        time = (re.search(r"\*\*Tijd:\*\* ([^·]+)", meta) or [None, ""])[1].strip()
        level = (re.search(r"\*\*Niveau:\*\* ([^·]+)", meta) or [None, ""])[1].strip()
        objectives_block = md.split("## 1. Leerdoelen", 1)[1].split("\n## ", 1)[0]
        objectives = [re.sub(r"\*\*|`", "", m) for m in re.findall(r"^\d+\. (.+)$", objectives_block, re.M)]
        quiz = parse_quiz((readme.parent / "quiz.md").read_text(encoding="utf-8"))
        key = parse_key((ROOT / f"learning/answer-keys/{slug}.md").read_text(encoding="utf-8"), "learning/answer-keys")
        for q in quiz:
            q.update(key[q["id"]])
        modules.append({
            "slug": slug,
            "number": int(slug[:2]),
            "title": re.sub(r"^Module \d+ — ", "", title),
            "level": level,
            "time": time,
            "objectives": objectives,
            "url": f"{BLOB}learning/modules/{slug}/README.md",
            "quiz": quiz,
        })
    return {"source": "learning/ (Markdown) — generated by scripts/build_learning.py", "modules": modules}


def main() -> int:
    text = json.dumps(build(), ensure_ascii=False, indent=1) + "\n"
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("site/learning/learning-data.json is out of date. Run: python3 scripts/build_learning.py")
            return 1
        print("Learning data up to date.")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    data = json.loads(text)
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(data['modules'])} modules, {sum(len(m['quiz']) for m in data['modules'])} questions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
